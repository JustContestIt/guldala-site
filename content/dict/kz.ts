const dayAndMonth = (iso: string) => {
  const [, m, d] = almatyDay(new Date(iso)).split("-").map(Number);
  return [d, m - 1] as const;
};
const until = (iso: string) => {
  const [d, m] = dayAndMonth(iso);
  return `${d} ${DATIVE[m]} дейін`;
};
const since = (iso: string) => {
  const [d, m] = dayAndMonth(iso);
  return `${d} ${ABLATIVE[m]} бастап`;
};

